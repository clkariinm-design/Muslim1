    fun inferTimezoneId(countryCode: String?, latitude: Double, longitude: Double): String {
        val upper = countryCode?.trim()?.uppercase()
        if (!upper.isNullOrEmpty()) {
            singleZoneCountryMap[upper]?.let { return it }
            // Check nearest curated city in the same country (helpful for multi-timezone countries like US, CA, ID, RU, AU)
            val sameCountryNearest = cities
                .filter { it.countryCode.equals(upper, ignoreCase = true) }
                .minByOrNull { CuratedCities.distanceKm(latitude, longitude, it.latitude, it.longitude) }
            if (sameCountryNearest != null) return sameCountryNearest.timezoneId
        }
        val nearestClose = CuratedCities.findNearestCity(latitude, longitude, maxDistanceKm = 350.0)
        if (nearestClose != null) return nearestClose.timezoneId
        val offsetHours = (longitude / 15.0).roundToInt().coerceIn(-12, 14)
        return when {
            offsetHours == 0 -> "UTC"
            offsetHours > 0 -> "Etc/GMT-$offsetHours" // Note: POSIX Etc/GMT signs are inverted
            else -> "Etc/GMT+${-offsetHours}"
        }
    }
